#!/usr/bin/env python3
"""Resolve runtime profiles and refresh provenance only after successful resolution."""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess
import sys
from datetime import date

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.services.lockfile import parse_requirements
from scripts.normalize_lock_hashes import normalize_hashes


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--uv', default='uv')
    parser.add_argument('--python', default=str(ROOT / 'app/env/bin/python'))
    args = parser.parse_args()
    source = ROOT / 'app/requirements.txt'
    cpu = source.read_text().splitlines()
    cpu = [line.replace('rembg[gpu]', 'rembg[cpu]') for line in cpu
           if not line.startswith(('--extra-index-url ', 'onnxruntime-gpu'))]
    locks = ROOT / 'app/locks'
    (locks / 'requirements.E0.in').write_text(
        '# CPU profile derived by scripts/refresh_runtime_locks.py\n' + '\n'.join(cpu) + '\n')
    for profile, requirements, constraints, index, filename in [
        ('E0', 'app/locks/requirements.E0.in', 'E0.cpu-py311.constraints.txt', 'cpu', 'E0.cpu-only.txt'),
        ('E3', 'app/requirements.txt', 'E3.cuda130-py311.constraints.txt', 'cu130', 'E3.cuda130-py311.txt'),
    ]:
        target = locks / filename
        temporary = target.with_suffix('.resolved')
        subprocess.run([args.uv, 'pip', 'compile', requirements, '--constraint', str(locks / constraints),
                        '--python', args.python, '--extra-index-url', f'https://download.pytorch.org/whl/{index}',
                        '--index-strategy', 'unsafe-best-match', '--find-links', 'app/.cache/runtime-wheels',
                        '--emit-index-url', '--generate-hashes', '--output-file', str(temporary)], cwd=ROOT, check=True,
                       stdout=subprocess.DEVNULL)
        target.write_text(normalize_hashes(temporary.read_text()))
        temporary.unlink()
    # GPU VRAM profiles intentionally use the same resolved CUDA ABI.
    gpu = (locks / 'E3.cuda130-py311.txt').read_text()
    for filename in ('E1.4gb-3050.txt', 'E2.6-8gb.txt', 'E4.16-24gb.txt'):
        (locks / filename).write_text('# GPU ABI shared with E3; generated by refresh_runtime_locks.py\n' + gpu)
    manifest_path = locks / 'source-manifest.json'
    manifest = json.loads(manifest_path.read_text())
    version = subprocess.check_output([args.uv, '--version'], text=True).strip()
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    for profile, entry in manifest['profiles'].items():
        lock = ROOT / entry['lock']
        path = ROOT / entry['manifest']
        provenance = json.loads(path.read_text())
        provenance.update(lock_sha256=digest(lock), requirements_txt_sha256=digest(source),
                          pyproject_sha256=digest(ROOT / 'pyproject.toml'), commit_sha=commit,
                          pip_version=version, resolved_at=date.today().isoformat())
        provenance['notes'].append('Re-resolved current requirements; previous installation evidence is historical until revalidated.')
        path.write_text(json.dumps(provenance, indent=2) + '\n')
        entry['packages'] = len(parse_requirements(lock.read_text()))
        for key in ('strict_hash_install', 'dependency_check', 'runtime_imports'):
            entry[key] = 'pending revalidation of refreshed lock'
    manifest['generated_at'] = date.today().isoformat()
    manifest['resolver'] = version
    manifest['validation']['status'] = 'Refreshed locks resolved; historical installation evidence retained separately'
    manifest['requirements_count'] = manifest['profiles']['E3']['packages']
    for name in manifest['source_sha256']:
        manifest['source_sha256'][name] = digest(ROOT / name)
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    runtime_path = ROOT / 'app/runtime_manifest.json'
    runtime = json.loads(runtime_path.read_text())
    runtime['python'] = '==3.11.*'
    runtime['requirementsSha256'] = digest(source)
    runtime['locks'] = {profile: {'path': str(Path(entry['lock']).relative_to('app')),
                                  'sha256': digest(ROOT / entry['lock'])}
                        for profile, entry in manifest['profiles'].items() if profile in ('E0', 'E3')}
    runtime_path.write_text(json.dumps(runtime, indent=2) + '\n')


if __name__ == '__main__':
    main()
